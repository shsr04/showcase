// Note: derives per-building keep-out rects from the built models; `node scripts/garden-footprints.mjs` prints, `--write` regenerates public/garden/js/footprints.js, `--check` fails when the table is stale.
import { register } from 'node:module';
import { pathToFileURL, fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const threeUrl = pathToFileURL(path.join(root, 'public/garden/vendor/three.module.js')).href;
const hook = `export async function resolve(s, c, next) {
  if (s === 'three') return { url: ${JSON.stringify(threeUrl)}, shortCircuit: true };
  return next(s, c);
}`;
register(`data:text/javascript,${encodeURIComponent(hook)}`, import.meta.url);

const THREE = await import('three');
const M = await import(pathToFileURL(path.join(root, 'public/garden/js/models.js')).href);
const CFG = await import(pathToFileURL(path.join(root, 'public/garden/js/config.js')).href);

// Note: a body stands about 0.7 tall; prims that start above the knee band or end below the ankle do not block.
const Y0 = 0.08;
const Y1 = 0.6;
const R3 = (v) => Math.round(v * 100) / 100;
const _v = new THREE.Vector3();

function primsOf(mesh) {
  let prims = mesh.geometry.userData.prims;
  if (!Array.isArray(prims) || !prims.length) {
    mesh.geometry.computeBoundingBox();
    const b = mesh.geometry.boundingBox;
    prims = [[b.min.x, b.min.y, b.min.z, b.max.x, b.max.y, b.max.z]];
  }
  return prims.map((p) => {
    const o = [Infinity, Infinity, Infinity, -Infinity, -Infinity, -Infinity];
    for (let k = 0; k < 8; k++) {
      _v.set(k & 1 ? p[3] : p[0], k & 2 ? p[4] : p[1], k & 4 ? p[5] : p[2]).applyMatrix4(mesh.matrixWorld);
      for (let a = 0; a < 3; a++) { o[a] = Math.min(o[a], _v.getComponent(a)); o[a + 3] = Math.max(o[a + 3], _v.getComponent(a)); }
    }
    return o;
  });
}

// Note: glow, smoke and similar meshes carry no solid body; only vertex-lit shell meshes count.
function solidPrims(g) {
  const out = [];
  g.traverse((o) => { if (o.isMesh && o.material && (o.material === M.MATS.vertex || o.material === M.MATS.vertexDouble)) out.push(...primsOf(o)); });
  return out;
}

const table = {};
const ids = Object.keys(CFG.BUILDINGS).filter((id) => !['stairs', 'art'].includes(id));
for (const id of ids) {
  const size = CFG.BUILDINGS[id].size;
  const hsz = size / 2;
  table[id] = [];
  for (let tier = 0; tier <= 4; tier++) {
    // Note: the airdock keep-out is its land block for every tier; the pier over the void blocks nobody.
    if (tier > 0 && (id === 'airdock' || !CFG.FLOURISH_IDS.has(id))) { table[id].push(table[id][0]); continue; }
    const u = [Infinity, Infinity, -Infinity, -Infinity];
    for (const lvl of id === 'hut' ? [0, 1, 2] : [0]) for (let seed = 0; seed < 8; seed++) {
      const g = M.makeBuilding(id, lvl, seed, tier);
      g.updateMatrixWorld(true);
      for (const p of solidPrims(g)) {
        if (p[4] < Y0 || p[1] > Y1) continue;
        if (id === 'airdock' && (p[0] >= hsz || p[5] > hsz + 0.5 || p[2] < -hsz - 0.5)) continue;
        // Note: thin props (rods, rails) under 0.06 wide in both axes are ignored.
        if (p[3] - p[0] < 0.06 && p[5] - p[2] < 0.06) continue;
        u[0] = Math.min(u[0], p[0]); u[1] = Math.min(u[1], p[2]); u[2] = Math.max(u[2], p[3]); u[3] = Math.max(u[3], p[5]);
      }
    }
    if (id === 'airdock') for (let k = 0; k < 4; k++) u[k] = Math.max(-hsz, Math.min(hsz, u[k]));
    table[id].push(u.every(Number.isFinite) ? u.map(R3) : [-hsz, -hsz, hsz, hsz]);
  }
}

if (process.argv.includes('--print')) {
  for (const id of ids) {
    const h = CFG.BUILDINGS[id].size / 2;
    console.log(id.padEnd(12), `half ${h}`, table[id].map((r) => `[${r.join(',')}]`).join(' '));
  }
}

const body = `// Note: generated by scripts/garden-footprints.mjs from the building models; do not edit by hand.\n// Note: keep-out rect [x0, z0, x1, z1] per id and tier 0..4, local to the building centre, +z = door side, before yaw.\nexport const KEEP = ${JSON.stringify(table).replace(/\],"/g, '],\n  "').replace('{"', '{\n  "').replace(/\}$/, '\n}')};\n`;
const out = path.join(root, 'public/garden/js/footprints.js');
if (process.argv.includes('--write')) { fs.writeFileSync(out, body); console.log('wrote', out); }
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('FAIL: footprints.js is stale; run node scripts/garden-footprints.mjs --write'); process.exit(1); }
  console.log('footprints.js up to date');
}
