function libraryById(libraryId) {
    return LANE_LIBRARIES[libraryId] || LANE_LIBRARIES[LANE_LIBRARY_ORDER[0]];
}

function cloneLibraryLanes(library, previousLanes = null, preserveLevels = false) {
    return library.lanes.map(lane => {
        const previous = previousLanes?.find(item => item.id === lane.id);
        const level = preserveLevels && previous ? previous.level : lane.enabled ? lane.level : 0;
        const lastNonZeroLevel = preserveLevels && previous
            ? previous.lastNonZeroLevel || previous.defaultLevel || lane.level
            : lane.level;

        return {
            ...lane,
            notes: lane.notes ? [...lane.notes] : undefined,
            level,
            enabled: level > LANE_OFF_LEVEL,
            defaultLevel: lane.level,
            lastNonZeroLevel,
            pattern: normalizePattern(lane.pattern),
            lastPulse: 0,
        };
    });
}
