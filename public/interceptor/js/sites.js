// Note: pads rows to equal width and resolves legend and markers into a tile grid plus spawns.
export function compileTemplate(rows, legend = LEGEND, markers = MARKERS) {
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const grid = new Uint8Array(w * h).fill(255);
  const spawns = [];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x] ?? ' ';
      if (markers[ch]) {
        grid[y * w + x] = markers[ch][0];
        spawns.push({ kind: markers[ch][1], x, y, ch });
      } else if (legend[ch] != null) {
        grid[y * w + x] = legend[ch];
      }
    }
  }
  return { w, h, grid, spawns };
}

// Note: a site is its tile-grid ground plus cell-grid buildings; `at` is a block's top-left cell in the template.
export function compileSite(tpl) {
  const c = compileTemplate(tpl.rows);
  c.builds = (tpl.build || []).map((b) => ({ ax: b.at[0], ay: b.at[1], ...compileTemplate(b.rows) }));
  return c;
}
